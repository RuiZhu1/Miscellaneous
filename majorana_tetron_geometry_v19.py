def sample_unit_paired_disorder(
    L1: int,
    L2: int,
    rho_site: float,
    xi_noise: float,
    n_real: int,
    seed: int,
) -> Tuple[np.ndarray, np.ndarray]:
    """Generate paired disorder at W=1 so multiple W values share realizations."""
    if n_real <= 0:
        raise ValueError("n_real must be positive")
    sampler = PairedSiteNoiseSampler(L1, L2, 1.0, rho_site, xi_noise, seed)
    return sampler.sample(n_real)


def _center_cov(a: np.ndarray, b: np.ndarray) -> float:
    a = np.asarray(a, dtype=float)
    b = np.asarray(b, dtype=float)
    if a.size != b.size or a.size < 2:
        return float("nan")
    aa = a - np.mean(a)
    bb = b - np.mean(b)
    return float(np.dot(aa, bb) / (a.size - 1))


def fourth_cumulant(x: np.ndarray) -> float:
    x = np.asarray(x, dtype=float)
    if x.size < 2:
        return float("nan")
    z = x - np.mean(x)
    m2 = float(np.mean(z**2))
    m4 = float(np.mean(z**4))
    return float(m4 - 3.0 * m2**2)


def loglog_slope(x: Sequence[float], y: Sequence[float]) -> float:
    xa = np.asarray(x, dtype=float)
    ya = np.asarray(y, dtype=float)
    mask = (xa > 0) & (ya > 0) & np.isfinite(xa) & np.isfinite(ya)
    if np.count_nonzero(mask) < 2:
        return float("nan")
    return float(np.polyfit(np.log(xa[mask]), np.log(ya[mask]), 1)[0])


def polynomial_directional_bdg_expansion(
    wire1: BdGWire,
    wire2: BdGWire,
    ref1: np.ndarray,
    ref2: np.ndarray,
    K1: np.ndarray,
    K2: np.ndarray,
    W_values: Sequence[float],
    rho_site: float,
    xi_noise: float,
    n_real: int,
    seed: int,
    probe_fraction: float = 0.10,
) -> Dict[str, object]:
    """Extract directional Taylor coefficients through fourth order.

    For a fixed unit-disorder direction d, full BdG is evaluated at amplitudes
    {-2h,-h,0,+h,+2h}; a degree-four polynomial in u is fitted to
        epsilon(u h d) = epsilon_0 + c1 u + c2 u^2 + c3 u^3 + c4 u^4.
    At physical amplitude W the coefficient sectors are c_n (W/h)^n.
    Independent exact full-BdG epsilon(W d) values are also evaluated at every
    W and are used as the gold-standard reference.
    """
    W_values = [float(w) for w in W_values if float(w) > 0]
    if len(W_values) < 2:
        raise ValueError("need at least two positive W values")
    if not (0.0 < probe_fraction < 0.5):
        raise ValueError("probe_fraction must lie in (0,0.5)")
    h = max(probe_fraction * max(W_values), 5e-4)

    d1_unit, d2_unit = sample_unit_paired_disorder(
        wire1.p.L, wire2.p.L, rho_site, xi_noise, n_real, seed
    )
    eps01 = float(wire1.signed_epsilon(None, reference_basis=ref1))
    eps02 = float(wire2.signed_epsilon(None, reference_basis=ref2))

    u = np.array([-2.0, -1.0, 0.0, 1.0, 2.0], dtype=float)
    V = np.column_stack([np.ones(5), u, u**2, u**3, u**4])
    Vinv = la.inv(V)

    c = [np.empty(n_real, dtype=float) for _ in range(8)]
    probe_res1 = np.empty(n_real, dtype=float)
    probe_res2 = np.empty(n_real, dtype=float)
    for r in range(n_real):
        d1 = d1_unit[r]; d2 = d2_unit[r]
        y1 = np.array([float(wire1.signed_epsilon((uk*h)*d1, reference_basis=ref1)) for uk in u])
        y2 = np.array([float(wire2.signed_epsilon((uk*h)*d2, reference_basis=ref2)) for uk in u])
        a1 = Vinv @ (y1 - eps01)
        a2 = Vinv @ (y2 - eps02)
        c[0][r], c[1][r], c[2][r], c[3][r] = a1[1], a1[2], a1[3], a1[4]
        c[4][r], c[5][r], c[6][r], c[7][r] = a2[1], a2[2], a2[3], a2[4]
        probe_res1[r] = float(np.max(np.abs(y1 - (eps01 + V @ a1))))
        probe_res2[r] = float(np.max(np.abs(y2 - (eps02 + V @ a2))))
    c1_1, c2_1, c3_1, c4_1, c1_2, c2_2, c3_2, c4_2 = c

    hf1 = d1_unit @ K1
    hf2 = d2_unit @ K2
    hf_err1 = c1_1 / h - hf1
    hf_err2 = c1_2 / h - hf2

    rows: List[Dict[str, object]] = []
    saved: Dict[str, Dict[str, np.ndarray]] = {}
    for W in W_values:
        rW = W / h
        L1 = c1_1 * rW; L2 = c1_2 * rW
        Q1 = c2_1 * rW**2; Q2 = c2_2 * rW**2
        R3_1 = c3_1 * rW**3; R3_2 = c3_2 * rW**3
        R4_1 = c4_1 * rW**4; R4_2 = c4_2 * rW**4
        E1 = np.empty(n_real, dtype=float); E2 = np.empty(n_real, dtype=float)
        for r in range(n_real):
            E1[r] = float(wire1.signed_epsilon(W*d1_unit[r], reference_basis=ref1))
            E2[r] = float(wire2.signed_epsilon(W*d2_unit[r], reference_basis=ref2))

        C2 = _center_cov(L1, L2)
        C3 = _center_cov(L1, Q2) + _center_cov(Q1, L2)
        C4 = _center_cov(L1, R3_2) + _center_cov(R3_1, L2) + _center_cov(Q1, Q2)
        C234 = C2 + C3 + C4
        C_exact = _center_cov(E1, E2)

        parity: Dict[str, Dict[str, float]] = {}
        for parity_value in (+1, -1):
            z1 = -(L1 + parity_value*L2)
            z2 = -((L1 + Q1) + parity_value*(L2 + Q2))
            z4 = -((L1 + Q1 + R3_1 + R4_1) + parity_value*(L2 + Q2 + R3_2 + R4_2))
            ze = -(E1 + parity_value*E2)
            parity[str(parity_value)] = {
                "var_z1": float(np.var(z1-np.mean(z1), ddof=1)),
                "var_z2": float(np.var(z2-np.mean(z2), ddof=1)),
                "var_z4": float(np.var(z4-np.mean(z4), ddof=1)),
                "var_z_exact": float(np.var(ze-np.mean(ze), ddof=1)),
                "kappa4_z1": fourth_cumulant(z1),
                "kappa4_z2": fourth_cumulant(z2),
                "kappa4_z4": fourth_cumulant(z4),
                "kappa4_z_exact": fourth_cumulant(ze),
            }
        rows.append({
            "W": W,
            "C2": float(C2), "C3": float(C3), "C4": float(C4),
            "C234": float(C234), "C_exact": float(C_exact),
            "C_exact_minus_C234": float(C_exact-C234),
            "probe_max_residual_wire1": float(np.max(probe_res1)),
            "probe_max_residual_wire2": float(np.max(probe_res2)),
            "hf_directional_rmse_wire1": float(np.sqrt(np.mean(hf_err1**2))),
            "hf_directional_rmse_wire2": float(np.sqrt(np.mean(hf_err2**2))),
            "hf_directional_corr_wire1": safe_corr(c1_1/h, hf1),
            "hf_directional_corr_wire2": safe_corr(c1_2/h, hf2),
            "parity": parity,
        })
        saved[str(W)] = {
            "L1": L1, "L2": L2, "Q1": Q1, "Q2": Q2,
            "R3_1": R3_1, "R3_2": R3_2, "R4_1": R4_1, "R4_2": R4_2,
            "eps1_exact": E1, "eps2_exact": E2,
        }

    W_arr = np.asarray([r["W"] for r in rows], dtype=float)
    k4_plus = np.abs([r["parity"]["1"]["kappa4_z_exact"] for r in rows])
    k4_minus = np.abs([r["parity"]["-1"]["kappa4_z_exact"] for r in rows])
    return {
        "rows": rows,
        "probe_amplitude": h,
        "probe_fraction": probe_fraction,
        "power_exponent_abs_C2": loglog_slope(W_arr, np.abs([r["C2"] for r in rows])),
        "power_exponent_abs_C3": loglog_slope(W_arr, np.abs([r["C3"] for r in rows])),
        "power_exponent_abs_C4": loglog_slope(W_arr, np.abs([r["C4"] for r in rows])),
        "power_exponent_abs_C_exact_minus_C234": loglog_slope(W_arr, np.abs([r["C_exact_minus_C234"] for r in rows])),
        "power_exponent_abs_kappa4_exact_plus": loglog_slope(W_arr, k4_plus),
        "power_exponent_abs_kappa4_exact_minus": loglog_slope(W_arr, k4_minus),
        "saved": saved,
        "eps0": {"wire1": eps01, "wire2": eps02},
        "hessian_direction_method": "5-point degree-4 local directional polynomial fit",
    }


def coherence_from_phase_samples(
    phase_frequency: np.ndarray,
    g: float,
    times: Sequence[float],
) -> np.ndarray:
    """Coherence for a supplied frequency-shift sample array."""
    phase_frequency = np.asarray(phase_frequency, dtype=float)
    out = np.empty(len(times), dtype=float)
    for j, t in enumerate(np.asarray(times, dtype=float)):
        out[j] = abs(np.mean(np.exp(-1j * phase_frequency * t)))
    return out


def half_lives_from_epsilon_model(
    e12: np.ndarray,
    e34: np.ndarray,
    g: float,
    n_time: int = 900,
) -> Dict[str, float]:
    e12 = np.asarray(e12, dtype=float)
    e34 = np.asarray(e34, dtype=float)
    d12 = e12 - np.mean(e12)
    d34 = e34 - np.mean(e34)
    out: Dict[str, float] = {}
    Svals = {}
    for p in (+1, -1):
        z = -(d12 + p * d34)
        S = float(np.var(z, ddof=1))
        Svals[str(p)] = S
    finite = [quadratic_half_life(g, S) for S in Svals.values() if S > 0]
    scale = max(finite) if finite else 1.0
    times = np.linspace(0.0, 1.35 * max(scale, 1.0), n_time)
    for p in (+1, -1):
        z = -(d12 + p * d34)
        omega_shift = np.sqrt(g**2 + z**2) - g
        coh = coherence_from_phase_samples(omega_shift, g, times)
        out[f"T{p:+d}"] = first_crossing(coh, times)
    out["Tplus"] = out["T+1"]
    out["Tminus"] = out["T-1"]
    out["C_lifetime"] = (
        covariance_inversion_from_half_lives(g, out["Tplus"], out["Tminus"])
        if np.isfinite(out["Tplus"]) and np.isfinite(out["Tminus"])
        else float("nan")
    )
    out["eta_lifetime"] = (
        eta_from_half_lives(out["Tplus"], out["Tminus"])
        if np.isfinite(out["Tplus"]) and np.isfinite(out["Tminus"])
        else float("nan")
    )
    out["S_plus"] = Svals["1"]
    out["S_minus"] = Svals["-1"]
    return out


