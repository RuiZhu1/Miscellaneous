def v18_surrogate_half_lives(
    expansion_row: Dict[str, object],
    g: float,
    n_time: int = 900,
) -> Dict[str, object]:
    """Compare O(W^2), kinematic O(W^4), coupling-nonlinear and exact BdG."""
    W = float(expansion_row["W"])
    L1 = np.asarray(expansion_row["_L1"], dtype=float)
    L2 = np.asarray(expansion_row["_L2"], dtype=float)
    Q1 = np.asarray(expansion_row["_Q1"], dtype=float)
    Q2 = np.asarray(expansion_row["_Q2"], dtype=float)
    R3_1 = np.asarray(expansion_row["_R3_1"], dtype=float)
    R3_2 = np.asarray(expansion_row["_R3_2"], dtype=float)
    R4_1 = np.asarray(expansion_row["_R4_1"], dtype=float)
    R4_2 = np.asarray(expansion_row["_R4_2"], dtype=float)
    E1 = np.asarray(expansion_row["_eps1_exact"], dtype=float)
    E2 = np.asarray(expansion_row["_eps2_exact"], dtype=float)
    scales=[]
    for p in (+1,-1):
        z=-(L1+p*L2); z-=np.mean(z)
        scales.append(quadratic_half_life(g,float(np.var(z,ddof=1))))
    scale=max([x for x in scales if np.isfinite(x) and x>0], default=1.0)
    times=np.linspace(0,1.35*max(scale,1.0),n_time)
    out={"W":W}
    for p in (+1,-1):
        z1=-(L1+p*L2); z1-=np.mean(z1)
        z2=-((L1+Q1)+p*(L2+Q2)); z2-=np.mean(z2)
        z4=-((L1+Q1+R3_1+R4_1)+p*(L2+Q2+R3_2+R4_2)); z4-=np.mean(z4)
        ze=-(E1+p*E2); ze-=np.mean(ze)
        f2=z1**2/(2*g)
        f24=f2-z1**4/(8*g**3)
        f_c2=z2**2/(2*g)
        f4=z4**2/(2*g)-z4**4/(8*g**3)
        fex=np.sqrt(g**2+ze**2)-g
        curves={
            "T2":coherence_from_phase_samples(f2,g,times),
            "T2plus4_gap":coherence_from_phase_samples(f24,g,times),
            "T2plus_coupling":coherence_from_phase_samples(f_c2,g,times),
            "T4_full":coherence_from_phase_samples(f4,g,times),
            "Texact":coherence_from_phase_samples(fex,g,times),
        }
        out[f"p{p:+d}"]={k:first_crossing(v,times) for k,v in curves.items()}
    # Convert each surrogate's two parity lifetimes back into an inferred C.
    out["C_from_model"] = {}
    for model in ("T2", "T2plus4_gap", "T2plus_coupling", "T4_full", "Texact"):
        tp = out["p+1"][model]
        tm = out["p-1"][model]
        out["C_from_model"][model] = (
            covariance_inversion_from_half_lives(g, tp, tm)
            if np.isfinite(tp) and np.isfinite(tm) else float("nan")
        )
    return out


