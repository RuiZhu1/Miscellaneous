"""Majorana-tetron geometric noise-transfer / antithetic nonlinear hierarchy v19.

v19 is a focused statistical-identification build.  Its sole scientific question is whether

the full-BdG mismatch between direct covariance and lifetime-inferred
covariance is controlled by the next nonlinear order of the sweet-spot
expansion, rather than being an unexplained failure of the transfer picture.

Core hierarchy
--------------
At an intrawire sweet spot epsilon_a*=0, expand a signed Majorana splitting
under local chemical-potential disorder delta_mu as

    delta epsilon_a = L_a + Q_a + O(W^3),

    L_a = K_a^T delta_mu,

    Q_a = 1/2 delta_mu^T H_a delta_mu.

For a paired Gaussian site-noise model,

    C_2 = Cov(L_1, L_2) = K_1^T Sigma_mu K_2,

and a directly measurable fourth-order covariance correction is defined by

    C_3 = Cov(L_1,Q_2)+Cov(Q_1,L_2),
    C_4 = Cov(Q_1,Q_2).

For centered Gaussian disorder, C_3 should vanish asymptotically and C_4
scales as W^4, while C_2 scales as W^2.

The parity-resolved sweet-spot coordinate is

    z_p = -(delta epsilon_12 + p delta epsilon_34),

with exact effective gap shift

    DeltaOmega = sqrt(g^2 + z_p^2) - g.

The leading and fourth-order frequency expansions are

    DeltaOmega_2   = z_p^2/(2g),
    DeltaOmega_4   = z_p^2/(2g) - z_p^4/(8g^3).

The quadratic Gaussian envelope is

    |W_p(t)| = [1 + (S_p t/g)^2]^(-1/4),

    S_p = sigma_12^2 + sigma_34^2 + 2 p C_2,

with

    T_1/2,p = sqrt(15) g/S_p.

v19 therefore tests four distinct objects:

1. Geometry-mediated second-order covariance:
       C_2 = K_1^T Sigma_mu K_2.
2. Nonlinear covariance hierarchy:
       C_exact = C_2 + C_3 + C_4 + higher orders.
3. Kinematic fourth-order correction in the gap expansion.
4. Whether the discrepancy
       Delta C_life(W)=C_lifetime(W)-C_direct(W)
   scales as W^4 at small W.

The code also reports the fourth cumulant

    kappa_4(z) = <(z-<z>)^4> - 3 Var(z)^2,

which diagnoses non-Gaussian effective coupling noise generated by nonlinear
mapping of Gaussian microscopic disorder.

Methodological safeguards
-------------------------
- Both wires are first tuned numerically to a real intrawire sweet spot.
- The first-order kernel uses degenerate perturbation theory inside the
  two-dimensional Majorana subspace at epsilon*=0, avoiding the derivative
  singularity of |epsilon|.
- Full finite-difference checks are retained.
- Nonlinear terms are extracted by symmetric +/- disorder directional probes:
      L(d) = [epsilon(+d)-epsilon(-d)]/2,
      Q(d) = [epsilon(+d)+epsilon(-d)]/2 - epsilon(0).
- The +/- directional probe uses a fixed clean-reference Majorana gauge, so the
  decomposition is local and does not rely on a re-gauged disorder sample.
- Direct full-BdG ensembles are kept separate from the 1M linearized kernel
  ensemble.
- The lifetime inversion is treated as a hypothesis test, not as an identity.
- p=+/- still labels total-parity sectors; this code does not silently equate
  them with two logical states of a fixed-parity tetron.
- g remains an externally specified bridge/control parameter.

No desired exponent is assumed in advance; the report is a falsification readout.  The report will
explicitly say whether the data support, weaken, or falsify the proposed W^4
correction.

Outputs
-------
The run writes JSON/NPZ/PNG files into --outdir, including:
    core_results_v19.json
    sensitivity_kernels_v19.npz
    fig1_v18_operating_point.png
    fig2_v18_kernels.png
    fig3_v18_W_scaling_and_mismatch.png
    fig4_v18_rho_transfer.png
    fig5_v18_geometry_design.png
    fig6_v18_dephasing_inversion.png
    fig7_v18_length_scan.png
    fig8_v18_nonlinear_decomposition.png
    fig9_v18_cumulant_scaling.png

Example
-------
python majorana_tetron_geometry_v18.py \\
    --outdir outputs_v18 \\
    --n-real 600 \\
    --mc 100000 \\
    --kernel-ensemble 1000000 \\
    --rho-site 0.60 \\
    --xi-noise 0.0 \\
    --W 0.03 \\
    --mu-scan-min 0.0 \\
    --mu-scan-max 1.5 \\
    --mu-scan-points 19
"""

